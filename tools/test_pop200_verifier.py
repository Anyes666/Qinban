    def test_optional_source_index_is_offline_and_title_artist_checked(self):
        rows = [(s["id"], s["title"], s["artist"]) for s in self.fixture.manifest["songs"]]
        def index_bytes(items):
            cell = lambda value, col, row: f'<c r="{col}{row}" t="inlineStr"><is><t>{escape(value)}</t></is></c>'
            header = '<row r="1">' + ''.join(cell(v, c, 1) for v, c in zip(("song_id", "name", "artist"), "ABC")) + '</row>'
            body = ''.join(f'<row r="{i}">' + ''.join(cell(v, c, i) for v, c in zip(values, "ABC")) + '</row>'
                           for i, values in enumerate(items, 2))
            xml = '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>' + header + body + '</sheetData></worksheet>'
            stream = io.BytesIO()
            with zipfile.ZipFile(stream, "w") as archive:
                archive.writestr("xl/worksheets/sheet1.xml", xml)
            return stream.getvalue()
        (self.fixture.intake / "index.xlsx").write_bytes(index_bytes(rows))
        self.assertTrue(self.fixture.run()["metadataIndexVerified"])
        rows[0] = (rows[0][0], "Wrong source index title", rows[0][2])
        (self.fixture.intake / "index.xlsx").write_bytes(index_bytes(rows))
        self.rejected("source index title/artist mismatch")

