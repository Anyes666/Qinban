def dump(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")


def vlq(value):
    result = [value & 127]
    while value >> 7:
        value >>= 7
        result.insert(0, 128 | (value & 127))
    return bytes(result)


def chunk(events):
    return b"MTrk" + len(events).to_bytes(4, "big") + events


def track_name(name):
    value = name.encode("utf-8")
    return b"\x00\xff\x03" + vlq(len(value)) + value


def midi_fixture(identity):
    """Two tempos, running note-off status, terminal rest, melody/bridge/drums."""
    pitch = 60 + int(identity) % 12
    tempo = track_name("TEMPO") + b"\x00\xff\x51\x03\x07\xa1\x20"
    tempo += vlq(480) + b"\xff\x51\x03\x09\x27\xc0" + vlq(1440) + b"\xff\x2f\x00"
    melody = track_name("MELODY") + b"\x00\xff\x01\x03" + identity.encode("ascii")
    melody += b"\x00\x90" + bytes([pitch, 70])
    melody += vlq(240) + b"\x80" + bytes([pitch, 0])
    melody += b"\x00\x90" + bytes([pitch + 4, 88])
    melody += vlq(240) + bytes([pitch + 4, 0])  # running 0x90 velocity-zero off
    melody += b"\x00\x90" + bytes([pitch + 7, 90])
    melody += vlq(480) + bytes([pitch + 7, 0])
    melody += vlq(480) + b"\xff\x2f\x00"
    bridge = track_name("BRIDGE") + b"\x00\x91\x30\x2d"
    bridge += vlq(960) + b"\x81\x30\x00\x00\x91\x37\x37"
    bridge += vlq(480) + b"\x81\x37\x00\x00\xff\x2f\x00"
    drums = track_name("DRUMS") + vlq(240) + b"\x99\x24\x32"
    drums += vlq(120) + b"\x89\x24\x00\x00\xff\x2f\x00"
    return b"MThd\x00\x00\x00\x06" + struct.pack(">HHH", 1, 4, 480) + b"".join(map(chunk, (tempo, melody, bridge, drums)))


